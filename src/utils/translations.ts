/**
 * Returns translated string for a key and language code.
 * Falls back to Hindi, then English if not found.
 */
export function t(key: string, langCode: string = 'en'): string {
  const entry = TRANSLATIONS[key];
  if (!entry) return key;

  const prefix = langCode.toLowerCase().split('-')[0];
  return entry[prefix] || entry['en'] || entry['hi'] || key;
}

/**
 * The core Regional / Language Formatter:
 * - When langCode is 'en' (English): returns purely the English string.
 * - When langCode is a regional language (hi, te, ta, kn, mr, bn, gu, pa, ml): returns ONLY the selected regional language translation.
 *   This ensures a clean, native experience where the user sees ONLY English or ONLY their chosen regional language.
 */
export function formatBilingual(
  english: string,
  key: string,
  langCode: string = 'en',
  style: 'slash' | 'parentheses' | 'stacked' = 'slash'
): string {
  const prefix = langCode.toLowerCase().split('-')[0];
  if (prefix === 'en') {
    return english;
  }

  // Guard against untranslated keys
  if (!TRANSLATIONS[key]) {
    return english;
  }

  const translated = t(key, prefix);
  if (!translated || translated === key) {
    return english;
  }

  // Return strictly the selected regional language translation
  return translated;
}

/**
 * Utility to parse strings containing multiple language representations (e.g. "English / Regional" or "English (Hindi / Telugu)")
 * and render strictly according to user's selected language:
 * - If user selected English: returns purely the English portion.
 * - If user selected a regional language: returns the corresponding regional portion if present, or cleanest available match.
 */
export function resolveBilingualString(
  rawText?: string,
  langCode: string = 'en'
): { primary: string; secondary?: string; display: string } {
  if (!rawText) return { primary: '', display: '' };

  const prefix = langCode.toLowerCase().split('-')[0];

  if (rawText.includes(' / ') || rawText.includes(' /')) {
    const parts = rawText.split(/\s*\/\s*/);
    const primary = parts[0]?.trim() || '';
    const secondary = parts.slice(1).join(' / ').trim();

    // If English is selected, only display the English part
    if (prefix === 'en') {
      return { primary, display: primary };
    }

    // When a regional language is selected, display the regional text
    return {
      primary: secondary || primary,
      secondary: primary,
      display: secondary || primary,
    };
  }

  return { primary: rawText, display: rawText };
}
